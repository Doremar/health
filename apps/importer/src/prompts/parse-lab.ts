export function buildParseLabPrompt(filePath: string): string {
  return `Ты парсер медицинских анализов из России. Тебе дан PDF-файл с результатом лабораторного исследования.

ШАГ 1. Обязательно используй инструмент Read, чтобы прочитать файл по абсолютному пути:
${filePath}

ШАГ 2. Внимательно изучи содержимое. В PDF могут быть: название лаборатории/клиники, дата сдачи, ФИО пациента, название панели/исследования, таблица показателей с референсными значениями.

ШАГ 3. Извлеки данные в строгом JSON по схеме:

{
  "date": "YYYY-MM-DD",
  "lab_name": "Invitro" | "KDL" | "CMD" | "Гемотест" | "Хеликс" | "ГКБ им. М.П. Кончаловского" | ... ,
  "panel": "биохимия крови" | "ОАК" | "клинический анализ мочи" | "гормоны щитовидной" | "глюкоза" | "холестерин" | "СОЭ" | null,
  "markers": [
    {
      "name": "Глюкоза",
      "value": 4.89,
      "value_text": null,
      "unit": "мМоль/л",
      "ref_low": 3.6,
      "ref_high": 6.4,
      "ref_text": null
    }
  ],
  "is_lab_result": true,
  "confidence": "high" | "medium" | "low"
}

Правила:
- date: дата сдачи биоматериала (если её нет, бери дату выдачи результата).
- lab_name: название учреждения как в шапке (медицинская клиника, лаборатория, ГКБ и т.п.).
- panel: краткое название исследования. Если в файле один показатель — назови по нему ("глюкоза", "холестерин", "СОЭ").
- value: число с точкой как разделителем (4.89, не "4,89"). Если значение не числовое (например, "отрицательно", "не обнаружено"), value: null и value_text: "отрицательно".
- ref_low/ref_high: оба числа. Если референс задан текстом ("не обнаружено", "до 5.0"), парси как сможешь: "до 5.0" → ref_low: null, ref_high: 5.0. Если совсем не число — оба null и заполни ref_text.
- unit: единица измерения как в бланке ("мМоль/л", "г/л", "10*9/л", "ng/ml").
- is_lab_result: true ВСЕГДА, если ты успешно прочитал PDF и увидел любые показатели/референсы/название лаборатории. false ТОЛЬКО если PDF — реально не анализ (квитанция, паспорт, пустая страница).
- confidence: "high" если все поля распознаны уверенно; "medium" если 1-2 поля под вопросом; "low" если значительная часть не распознана.

ШАГ 4. Выведи СТРОГО валидный JSON. Никаких пояснений до или после JSON. Никаких markdown-фенсов вроде \`\`\`json. Только сам объект.`;
}
