export function buildParseStudyPrompt(filePath: string): string {
  return `Ты парсер медицинских исследований (ЭКГ, холтер, СМАД, КТ, МРТ, рентген, флюорография, УЗИ).

ШАГ 1. Прочитай файл инструментом Read по пути:
${filePath}

ШАГ 2. Извлеки данные в строгом JSON по схеме:

{
  "date": "YYYY-MM-DD",
  "type": "ecg" | "holter" | "smad" | "xray" | "fluorography" | "ct" | "mri" | "usg" | "other",
  "modality": "кардиология" | "лучевая" | "ультразвук" | null,
  "organ": "сердце" | "позвоночник L4-L5" | "печень" | null,
  "facility": "ГКБ им. М.П. Кончаловского" | null,
  "doctor": "Иванова И.И." | null,
  "conclusion": "Полный текст заключения врача...",
  "findings": "Описательная часть (что увидели до выводов)",
  "recommendations": "Рекомендации если есть",
  "diagnoses": [
    { "text": "Синусовый ритм, ЧСС 72 в мин", "icd10": null }
  ],
  "metrics": [
    { "code": "hr_avg", "name": "ЧСС средняя", "value": 72,
      "unit": "уд/мин", "ref_low": 60, "ref_high": 80 }
  ],
  "is_study": true,
  "confidence": "high" | "medium" | "low"
}

Правила:
- date: ISO дата проведения (если нет — дата выдачи заключения).
- type: один из 9 значений. Если непонятно — "other".
- modality: группа: "кардиология" для ECG/holter/SMAD, "лучевая" для xray/fluo/CT/MRI, "ультразвук" для USG.
- conclusion: полный текст заключения врача, дословно (1-3 абзаца).
- findings: описательная часть до выводов (что увидели), если есть отдельно.
- diagnoses: каждый диагноз отдельным элементом. icd10 если упомянут.
- metrics: только для ЭКГ/холтер/СМАД/УЗИ если в файле есть числа (ЧСС min/max/avg, ДАД, размеры). КТ/МРТ обычно metrics: [].
- code маркера: латинский slug (hr_avg, bp_sys_day, qt_ms, liver_size_cm).
- is_study: true ВСЕГДА если ты прочитал документ и это медицинское описательное исследование. false если квитанция/паспорт/случайное.
- confidence: high — всё распознано чётко; medium — 1-2 поля под вопросом; low — много пропусков.

Выведи СТРОГО валидный JSON. Без пояснений и markdown-фенсов.`;
}
