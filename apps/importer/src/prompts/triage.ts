export function buildTriagePrompt(filePath: string): string {
  return `Тебе дан медицинский PDF/фото. Определи тип документа.

ШАГ 1. Прочитай файл инструментом Read по пути: ${filePath}

ШАГ 2. Классифицируй по 3 категориям:
  (a) "lab" — ТАБЛИЦА ЛАБОРАТОРНЫХ МАРКЕРОВ:
      биохимия крови, общий анализ крови, мочи, гормоны, витамины.
      Каждая строка: "название показателя | значение | единицы | референс".
      Несколько чисел в табличной форме.
  (b) "study" — ОПИСАТЕЛЬНОЕ ИССЛЕДОВАНИЕ:
      ЭКГ, холтеровское мониторирование, СМАД, рентген, флюорография,
      КТ, МРТ, УЗИ. Текст заключения врача в свободной форме,
      опционально несколько чисел (ЧСС, размеры).
  (c) "other" — что-то ещё: квитанция, паспорт, скан непонятно чего.

ШАГ 3. Верни СТРОГО JSON по схеме:

{
  "kind": "lab" | "study" | "other",
  "confidence": "high" | "medium" | "low"
}

Никаких пояснений до или после. Только JSON.`;
}
